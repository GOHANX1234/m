package com.mna.streaming.ui.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * 4dp-based spacing scale. New or redesigned layouts should build paddings
 * and gaps from this scale instead of scattering ad-hoc dp literals, so
 * rhythm stays consistent from screen to screen.
 */
object MASpacing {
    val xxs: Dp = 2.dp
    val xs: Dp = 4.dp
    val sm: Dp = 8.dp
    val md: Dp = 12.dp
    val lg: Dp = 16.dp
    val xl: Dp = 20.dp
    val xxl: Dp = 24.dp
    val xxxl: Dp = 32.dp
}
